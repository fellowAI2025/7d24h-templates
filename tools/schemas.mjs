#!/usr/bin/env node
// Writes schemas/*.schema.json (JSON Schema 2020-12, for editors) from the
// specs in lib/schema.mjs, which is what CI enforces. --check fails when the
// files are out of date instead of writing them.
//
//   node tools/schemas.mjs [--check]
import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import path from 'node:path';

import { REPOSITORY, REPO_ROOT, ToolError, parseArgs, run, writeJson } from './lib/common.mjs';
import { CATEGORIES, MANIFEST, TYPAGE } from './lib/schema.mjs';

const SCHEMAS = [
  ['7d24h-template.v1.schema.json', 'manifest.json (7d24h-template/v1)', MANIFEST],
  ['typage-template.v1.schema.json', 'typage.json (typage-template/v1)', TYPAGE],
  ['7d24h-template-categories.v1.schema.json', 'categories.json (7d24h-template-categories/v1)', CATEGORIES],
];

function toJsonSchema(spec) {
  let schema;
  switch (spec.type) {
    case 'string':
      schema = { type: 'string', minLength: 1 };
      if (spec.max) schema.maxLength = spec.max;
      if (spec.pattern) schema.pattern = spec.pattern.source;
      break;
    case 'int':
      schema = { type: 'integer', minimum: spec.min ?? 0, maximum: spec.max };
      break;
    case 'number':
      schema = { type: 'number', minimum: spec.min, maximum: spec.max };
      break;
    case 'boolean':
      schema = { type: 'boolean' };
      break;
    case 'enum':
      schema = { enum: spec.values };
      break;
    case 'array':
      schema = { type: 'array', items: toJsonSchema(spec.items) };
      if (spec.max) schema.maxItems = spec.max;
      break;
    case 'map':
      schema = {
        type: 'object',
        propertyNames: toJsonSchema(spec.key),
        additionalProperties: toJsonSchema(spec.value),
      };
      if (spec.max) schema.maxProperties = spec.max;
      break;
    case 'object':
      schema = {
        type: 'object',
        properties: Object.fromEntries(Object.entries(spec.fields).map(([key, field]) => [key, toJsonSchema(field)])),
        required: Object.entries(spec.fields).filter(([, field]) => !field.optional).map(([key]) => key),
        additionalProperties: spec.open === true,
      };
      break;
    default:
      throw new Error(`bad spec ${spec.type}`);
  }
  if (spec.nullable) {
    if (schema.enum) schema.enum = [...schema.enum, null];
    else if (schema.type) schema.type = [schema.type, 'null'];
  }
  return schema;
}

run(async () => {
  const { options } = parseArgs(process.argv.slice(2), { check: 'boolean' });
  const dir = path.join(REPO_ROOT, 'schemas');
  mkdirSync(dir, { recursive: true });
  const stale = [];
  for (const [file, title, spec] of SCHEMAS) {
    const schema = {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      $id: `https://raw.githubusercontent.com/${REPOSITORY}/main/schemas/${file}`,
      title,
      description: 'Generated by tools/schemas.mjs from tools/lib/schema.mjs; do not edit.',
      ...toJsonSchema(spec),
    };
    const target = path.join(dir, file);
    const text = `${JSON.stringify(schema, null, 2)}\n`;
    if (options.check) {
      if (!existsSync(target) || readFileSync(target, 'utf8') !== text) stale.push(`schemas/${file}`);
    } else {
      writeJson(target, schema);
    }
  }
  if (stale.length) throw new ToolError(`out of date, run tools/schemas.mjs: ${stale.join(', ')}`);
  console.log(options.check ? 'schemas are up to date' : `wrote ${SCHEMAS.length} schemas`);
});
